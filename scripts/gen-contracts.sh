#!/usr/bin/env bash
# Planner tool: regenerate code from contracts/. Output is committed; the executor never runs this.
# Needs only Docker. Run from the repo root: scripts/gen-contracts.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/in"
for d in shared jobs events artifacts qdrant; do
  mkdir -p "$TMP/in/$d"
  cp "$ROOT"/contracts/$d/*.schema.json "$TMP/in/$d/"
done
docker run --rm -v "$TMP":/g -w /g python:3.12.16-slim sh -c '
  pip install -q --root-user-action=ignore --disable-pip-version-check datamodel-code-generator==0.87.0 &&
  datamodel-codegen --input in --input-file-type jsonschema --output out \
    --output-model-type pydantic_v2.BaseModel --use-annotated --field-constraints --extra-fields forbid \
    --target-python-version 3.12 --use-standard-collections --use-union-operator --disable-timestamp \
    --use-title-as-name --enum-field-as-literal all --use-double-quotes --use-type-alias 2>/dev/null'
for svc in api worker; do
  dest="$ROOT/services/$svc/src/rag_$svc/contracts_gen"
  rm -rf "$dest"
  cp -R "$TMP/out" "$dest"
  printf '# GENERATED by scripts/gen-contracts.sh from contracts/. Do not edit.\n' > "$dest/README"
done
docker run --rm -v "$ROOT/contracts":/contracts -v "$ROOT/services/web/src/api":/out node:24.19.0-slim \
  npx -y openapi-typescript@7.13.0 /contracts/openapi/api.yaml -o /out/schema.d.ts >/dev/null 2>&1
echo "generated: services/{api,worker}/src/rag_*/contracts_gen, services/web/src/api/schema.d.ts"
